        double[] dArr = new double[5];//결과: [][][][][]
        dArr[0] = 0.1; //결과: [0.1][][][][]
        dArr[1] = 0.2; //결과: [0.1][0.2][][][] > 숫자가 들어있지않은 나머지 상자에는 비어있음

        //tip) 배열의 길이와 인덱스의 크기는 다르다.
        //     즉, 인덱스의 크기는 n-1이다. 여기서 n은 배열의 길이를 의미한다.
        //배열의 길이가 30, 인덱스의 크기는 29
        //배열의 길이가 789, 인덱스의 크기는 788
        //현재 나와있는 모든 프로그램에서는 인덱스의 시작이 무조건 0부터이다.

