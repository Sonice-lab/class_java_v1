        //범위 밖의 길이에 선언했으나, 코드상으로는 오류가 나타나지 않음(컴파일 시점에서는 확인되지 않음)
        //실행시키는 순간(런타임시점) 오류가 인식됨
        //배열을 사용하는방법 2번째 형태
        //배열을 사용하려면 반드시 몇 칸 짜리를 만들어야 할 지 크기를 정해주어야 한다.
        // 배열 선언과 동시에 값까지 초기화하는 형태
        int[] gradArray = new int[]{1, 2, 3}; //  결과: [1][2][3]
        int[] gradArray2 = {2, 3, 4}; //new int[] 생략 가능 > 결과: [2][3][4]

